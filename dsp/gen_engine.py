def tables_asm():
    sext = [0 if i < 128 else 255 for i in range(256)]
    gts = T.gtabs()
    kt = T.ktab()
    fr = T.frac()
    sn = T.sin8()
    ni = T.note_inc()
    sel = T.gt_select()
    pal = [sid_freq(n, 984375.0) for n in range(96)]
    ntsc = [sid_freq(n, 1022727.27) for n in range(96)]

    def block(addr, vals):
        out = f"* = ${addr:04X}\n"
        for i in range(0, len(vals), 16):
            out += "        .byte " + ", ".join(str(v & 255) for v in vals[i:i + 16]) + "\n"
        return out
    s = "\n; ---------------- tables ----------------\n"
    s += block(0x4000, sext)
    for k, g in enumerate(gts):
        s += block(0x4100 + 0x200 * k, [v & 255 for v in g])
        s += block(0x4200 + 0x200 * k, [(v >> 8) & 255 for v in g])
    s += block(0x4700, [v & 255 for v in kt]) + block(0x4800, [v >> 8 for v in kt])
    s += block(0x4900, [v & 255 for v in fr]) + block(0x4A00, [v >> 8 for v in fr])
    s += block(0x4B00, [v & 255 for v in sn])
    s += block(0x4C00, [v & 255 for v in ni]) + block(0x4C80, [(v >> 8) & 255 for v in ni])
    s += block(0x4D00, [(v >> 16) & 255 for v in ni]) + block(0x4D80, sel)
    s += block(0x4E00, [v & 255 for v in pal]) + block(0x4E80, [v >> 8 for v in pal])
    s += block(0x4F00, [v & 255 for v in ntsc]) + block(0x4F80, [v >> 8 for v in ntsc])
    s += "* = $4FFF\nENG_END: .byte 0\n"
    return s


def sid_freq(note, clk):
    f = 440.0 * 2 ** ((note - 69) / 12)
    return min(0xFFFF, int(round(f * 2 ** 24 / clk)))


