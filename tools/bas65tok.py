DEFAULT_TABLE = Path(__file__).resolve().parent.parent / 'ref' / 'basic65' / 'appendix-keywords.tex'
LOAD_ADDRESS = 0x2001


def builtin_table():
    return {k: bytes.fromhex(v) for k, v in TOKENS.items()}


def read_table(path=None):
    """Keyword -> token bytes. Without a path: the built-in table. With a path: the 'Keywords
    And Tokens' tables of an appendix-keywords.tex, to check the built-in table against."""
    if path is None:
        return builtin_table()
    text = Path(path).read_text()
    part = text.split('Tokens And Keywords Part 1')[0]
    table = {}
    for row in part.splitlines():
        if '&' not in row or 'tabular' in row:
            continue
        cells = [c.strip() for c in row.replace('\\\\', '').split('&')]
        for kw, tok in zip(cells[0::2], cells[1::2]):
            if not kw or not tok:
                continue
            kw = kw.replace('\\string^', '^').replace('\\#', '#').replace('\\$', '$')
            if not re.fullmatch(r'[0-9A-F]{2}|[0-9A-F]{4}', tok):
                raise ValueError(f"bad token {tok!r} for {kw!r}")
            table[kw] = bytes.fromhex(tok)
    if len(table) < 180:
        raise ValueError(f"only {len(table)} keywords read from {path}")
    return table


def crunch_line(text, table, keys):
    out = bytearray()
    i, n = 0, len(text)
    quote = rem = data = False
    while i < n:
        c = text[i]
        if not 0x20 <= ord(c) <= 0x5E:
            raise ValueError(f"character {c!r} is not in the PETSCII-safe range")
        if rem:
            out.append(ord(c))
            i += 1
            continue
        if c == '"':
            quote = not quote
            out.append(0x22)
            i += 1
            continue
        if quote:
            out.append(ord(c))
            i += 1
            continue
        if data:
            if c == ':':
                data = False
            out.append(ord(c))
            i += 1
            continue
        if c == '$':
            out.append(0x24)
            i += 1
            while i < n and text[i] in '0123456789ABCDEF':
                out.append(ord(text[i]))
                i += 1
            continue
        kw = next((k for k in keys if text.startswith(k, i)), None)
        if kw is not None:
            out += table[kw]
            i += len(kw)
            if kw == 'REM':
                rem = True
            elif kw == 'DATA':
                data = True
            continue
        out.append(ord(c))
        i += 1
    if quote:
        pass    # an open string at the end of a line is legal BASIC
    return bytes(out)


def tokenise(listing_text, table):
    keys = sorted(table, key=len, reverse=True)
    lines = []
    for raw in listing_text.splitlines():
        if not raw.strip():
            continue
        m = re.match(r'^(\d+) (.*)$', raw)
        if not m:
            raise ValueError(f"bad line: {raw!r}")
        no = int(m.group(1))
        if lines and no <= lines[-1][0]:
            raise ValueError(f"line {no} out of order")
        if no > 63999:
            raise ValueError(f"line number {no} too big")
        lines.append((no, crunch_line(m.group(2), table, keys)))
    prog = bytearray()
    addr = LOAD_ADDRESS
    for no, body in lines:
        if len(body) > 255:
            raise ValueError(f"line {no} is {len(body)} bytes tokenised")
        nxt = addr + 4 + len(body) + 1
        prog += bytes([nxt & 255, nxt >> 8, no & 255, no >> 8]) + body + b'\x00'
        addr = nxt
    prog += b'\x00\x00'
    return bytes([LOAD_ADDRESS & 255, LOAD_ADDRESS >> 8]) + bytes(prog), len(lines)


def detokenise(prg, table):
    """PRG -> listing text, checking every link on the way."""
    rev = {v: k for k, v in table.items()}
    load = prg[0] | prg[1] << 8
    mem = prg[2:]
    out, pos = [], 0
    while True:
        link = mem[pos] | mem[pos + 1] << 8
        if link == 0:
            break
        no = mem[pos + 2] | mem[pos + 3] << 8
        p = pos + 4
        text, quote, rem, data = [], False, False, False
        while mem[p] != 0:
            b = mem[p]
            literal = True
            if rem:
                pass
            elif quote:
                quote = b != 0x22
            elif b == 0x22:
                quote = True
            elif data:
                data = b != ord(':')
            elif b >= 0x80:
                literal = False
            if literal:
                text.append(chr(b))
                p += 1
                continue
            if b in (0xCE, 0xFE):
                tok, p = bytes(mem[p:p + 2]), p + 2
            else:
                tok, p = bytes([b]), p + 1
            if tok not in rev:
                raise ValueError(f"line {no}: unknown token {tok.hex()}")
            kw = rev[tok]
            text.append(kw)
            if kw == 'REM':
                rem = True
            elif kw == 'DATA':
                data = True
        if load + p + 1 != link:
            raise ValueError(f"line {no}: link ${link:04X}, next line at ${load + p + 1:04X}")
        out.append(f"{no} {''.join(text)}")
        pos = p + 1
    if pos + 2 != len(mem):
        raise ValueError(f"{len(mem) - pos - 2} bytes after the end marker")
    return '\n'.join(out) + '\n'


def main():
    args = sys.argv[1:]
    if args and args[0] == '--list':
        table = read_table(args[2] if len(args) > 2 else None)
        sys.stdout.write(detokenise(Path(args[1]).read_bytes(), table))
        return
    src, out = args[0], args[1]
    table = read_table(args[2] if len(args) > 2 else None)
    prg, count = tokenise(Path(src).read_text(), table)
    Path(out).write_bytes(prg)
    end = LOAD_ADDRESS + len(prg) - 2
    print(f"{out}: {count} lines, {len(prg)} bytes, BASIC text ${LOAD_ADDRESS:04X}-${end - 1:04X}")


if __name__ == '__main__':
    main()
