"""bas65tok: numbered BASIC 65 listing -> tokenised PRG (load address $2001), and back.

The token table is built in (TOKENS below), copied from the MEGA65 User's Guide source,
appendix-keywords.tex, which the MEGA65 team generates from the ROM sources
(mega65-rom/tools/keywordref.py). Passing that file as TABLE.tex uses it instead.

Crunching follows the ROM's rules as documented and as VICE petcat implements them for BASIC 65:
- nothing is tokenised inside quotes, after REM to the end of the line, or after DATA up to the
  next colon outside quotes;
- after '$' the hex digits 0-9 and A-F are taken greedily as part of the number;
- elsewhere the longest keyword starting at the position is replaced by its token (one byte,
  or $CE/$FE and a second byte); the operators + - * / ^ < = > are tokens too;
- spaces and everything else are kept as they are.
Usage: python3 bas65tok.py LISTING.bas OUT.prg [TABLE.tex]
       python3 bas65tok.py --list IN.prg [TABLE.tex]     (detokenise, for checking)
"""
