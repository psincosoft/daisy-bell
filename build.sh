#!/bin/sh
# DAISY BELL: the streams, the engine, the BASIC program and the disk.
# Quick checks run here (the engine for 3 s against the model, the BASIC sessions); the whole show
# in the emulator takes about 20 minutes: python3 dsp/test_engine.py build --strict
set -e
cd "$(dirname "$0")"
B=${B:-build}
D81=${D81:-DAISY-BELL.D81}
export B
mkdir -p $B
# the voice and play streams, the show's timeline
(cd dsp && python3 song.py ../$B)
# the engine
(cd dsp && python3 gen_engine.py ../$B/engine.asm)
python3 tools/asm65.py $B/engine.asm $B/engine.bin $B/engine.lst $B/engine.sym
python3 - <<'PY'
import os
from pathlib import Path
B = Path(os.environ['B'])
eng = (B / 'engine.bin').read_bytes()
assert eng[3:6] == b'SNG' and len(eng) == 0x3000, 'engine signature or size'
(B / 'DAISY-BELL.ENG').write_bytes(bytes([0x00, 0x20]) + eng)
vox = (B / 'DAISY-BELL.VOX').read_bytes()[2:]
evt = (B / 'DAISY-BELL.EVT').read_bytes()[2:]
assert vox[-1] == 0xFF and evt[-2:] == b'\xff\x00', 'stream ends'
assert len(vox) <= 0x10000 and len(evt) <= 0x10000, 'a stream crosses its 64 KB bank'
Path('src/streams.b65').write_text(
    "# generated by build.sh from the build: where the streams end, the engine's version, the sample rate\n"
    f"#define VOX_LAST ${0x8000000 + len(vox) - 1:07X}\n"
    f"#define EVT_LAST ${0x8010000 + len(evt) - 2:07X}\n"
    f"#define ENGINE_VERSION {eng[6]}\n"
    f"#define SAMPLE_RATE {40500000 * 4142 / 16777216:.4f}\n")
print(f"DAISY-BELL.ENG {len(eng) + 2}, .VOX {len(vox) + 2}, .EVT {len(evt) + 2} bytes")
PY
# the engine for 3 s against the model (a failure stops the build; the log keeps the details)
(cd dsp && python3 test_engine.py ../$B 3 --strict > ../$B/test_3s.log)
tail -3 $B/test_3s.log
# the BASIC program (bas65pp checks names, labels, jumps, characters and lines of up to 160 characters)
python3 tools/bas65pp.py src/daisy-bell.b65 $B/daisy-bell.bas --width 160
python3 tools/bas65tok.py $B/daisy-bell.bas $B/daisy-bell.prg
python3 tools/bas65tok.py --list $B/daisy-bell.prg | diff - $B/daisy-bell.bas
(cd dsp && python3 run_sings.py ../$B > ../$B/run_sings.log)
tail -1 $B/run_sings.log
# the disk: the program first (LOAD"*"), AUTOBOOT.C65, the engine and the streams, credits, licence
python3 tools/make_d81.py --disk $B/$D81 "DAISY-BELL" DB \
    DAISY-BELL=$B/daisy-bell.prg:prg AUTOBOOT.C65=$B/daisy-bell.prg:prg \
    DAISY-BELL.ENG=$B/DAISY-BELL.ENG:prg DAISY-BELL.VOX=$B/DAISY-BELL.VOX:prg \
    DAISY-BELL.EVT=$B/DAISY-BELL.EVT:prg CREDITS=docs/CREDITS.txt:text80 LICENSE=docs/LICENSE.txt:text80
python3 tools/check_d81.py $B/$D81 DAISY-BELL=$B/daisy-bell.prg AUTOBOOT.C65=$B/daisy-bell.prg \
    DAISY-BELL.ENG=$B/DAISY-BELL.ENG DAISY-BELL.VOX=$B/DAISY-BELL.VOX DAISY-BELL.EVT=$B/DAISY-BELL.EVT
sha256sum $B/$D81
